WITH FLOC_HIERARCHY AS
(
    -- LEVEL 1
    SELECT
        F.TPLNR,
        F.TPLMA,
        1 AS HIERARCHY_LEVEL,

        CAST(F.TPLNR AS VARCHAR(100)) AS LEVEL_1_FLOC,
        CAST(NULL AS VARCHAR(100)) AS LEVEL_2_FLOC,
        CAST(NULL AS VARCHAR(100)) AS LEVEL_3_FLOC,
        CAST(NULL AS VARCHAR(100)) AS LEVEL_4_FLOC

    FROM SAP_IFLOT_DATA F
    WHERE F.TPLMA IS NULL
       OR LTRIM(RTRIM(F.TPLMA)) = ''

    UNION ALL

    -- LEVEL 2
    SELECT
        C.TPLNR,
        C.TPLMA,
        P.HIERARCHY_LEVEL + 1,

        CAST(P.LEVEL_1_FLOC AS VARCHAR(100)),
        CAST(C.TPLNR AS VARCHAR(100)),
        CAST(P.LEVEL_3_FLOC AS VARCHAR(100)),
        CAST(P.LEVEL_4_FLOC AS VARCHAR(100))

    FROM SAP_IFLOT_DATA C
    INNER JOIN FLOC_HIERARCHY P
        ON LTRIM(RTRIM(C.TPLMA)) = LTRIM(RTRIM(P.TPLNR))
    WHERE P.HIERARCHY_LEVEL = 1

    UNION ALL

    -- LEVEL 3
    SELECT
        C.TPLNR,
        C.TPLMA,
        P.HIERARCHY_LEVEL + 1,

        CAST(P.LEVEL_1_FLOC AS VARCHAR(100)),
        CAST(P.LEVEL_2_FLOC AS VARCHAR(100)),
        CAST(C.TPLNR AS VARCHAR(100)),
        CAST(P.LEVEL_4_FLOC AS VARCHAR(100))

    FROM SAP_IFLOT_DATA C
    INNER JOIN FLOC_HIERARCHY P
        ON LTRIM(RTRIM(C.TPLMA)) = LTRIM(RTRIM(P.TPLNR))
    WHERE P.HIERARCHY_LEVEL = 2

    UNION ALL

    -- LEVEL 4
    SELECT
        C.TPLNR,
        C.TPLMA,
        P.HIERARCHY_LEVEL + 1,

        CAST(P.LEVEL_1_FLOC AS VARCHAR(100)),
        CAST(P.LEVEL_2_FLOC AS VARCHAR(100)),
        CAST(P.LEVEL_3_FLOC AS VARCHAR(100)),
        CAST(C.TPLNR AS VARCHAR(100))

    FROM SAP_IFLOT_DATA C
    INNER JOIN FLOC_HIERARCHY P
        ON LTRIM(RTRIM(C.TPLMA)) = LTRIM(RTRIM(P.TPLNR))
    WHERE P.HIERARCHY_LEVEL = 3
)

SELECT
    H.LEVEL_1_FLOC,
    L1.PLTXT AS LEVEL_1_TEXT,

    H.LEVEL_2_FLOC,
    L2.PLTXT AS LEVEL_2_TEXT,

    H.LEVEL_3_FLOC,
    L3.PLTXT AS LEVEL_3_TEXT,

    H.LEVEL_4_FLOC,
    L4.PLTXT AS LEVEL_4_TEXT,

    F.IWERK AS PLANNING_PLANT,
    F.INGRP AS PLANNER_GROUP,
    F.LGWID AS WORK_CENTRE

FROM FLOC_HIERARCHY H

-- Get master data of the LAST/LEAF Functional Location
LEFT JOIN SAP_IFLOT_DATA F
    ON LTRIM(RTRIM(F.TPLNR)) = LTRIM(RTRIM(H.TPLNR))

LEFT JOIN SAP_IFLOTX_DATA L1
    ON LTRIM(RTRIM(L1.TPLNR)) = LTRIM(RTRIM(H.LEVEL_1_FLOC))
   AND L1.SPRAS = 'E'

LEFT JOIN SAP_IFLOTX_DATA L2
    ON LTRIM(RTRIM(L2.TPLNR)) = LTRIM(RTRIM(H.LEVEL_2_FLOC))
   AND L2.SPRAS = 'E'

LEFT JOIN SAP_IFLOTX_DATA L3
    ON LTRIM(RTRIM(L3.TPLNR)) = LTRIM(RTRIM(H.LEVEL_3_FLOC))
   AND L3.SPRAS = 'E'

LEFT JOIN SAP_IFLOTX_DATA L4
    ON LTRIM(RTRIM(L4.TPLNR)) = LTRIM(RTRIM(H.LEVEL_4_FLOC))
   AND L4.SPRAS = 'E'

-- ONLY RETURN THE LAST/LEAF LEVEL
WHERE NOT EXISTS
(
    SELECT 1
    FROM SAP_IFLOT_DATA CHILD
    WHERE LTRIM(RTRIM(CHILD.TPLMA)) = LTRIM(RTRIM(H.TPLNR))
)

ORDER BY
    H.LEVEL_1_FLOC,
    H.LEVEL_2_FLOC,
    H.LEVEL_3_FLOC,
    H.LEVEL_4_FLOC

OPTION (MAXRECURSION 100);